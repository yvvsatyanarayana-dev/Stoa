import React, { useState } from 'react'
import { useAppStore } from '../../store/useAppStore'
import { SolverSubjectRequirement, SolverResult } from '../../../../types'
import { Sparkles, X, CheckCircle2, AlertTriangle } from 'lucide-react'

export const AutoGenerateModal: React.FC = () => {
  const {
    isAutoGenerateModalOpen,
    setIsAutoGenerateModalOpen,
    activeTimetableId,
    subjects,
    resources,
    applyAutoGeneratedSlots
  } = useAppStore()

  const [selectedDays, setSelectedDays] = useState<number[]>([1, 2, 3, 4, 5])
  const [slotDuration, setSlotDuration] = useState<number>(60) // minutes
  const [dayStartTime, setDayStartTime] = useState<string>('09:00')
  const [dayEndTime, setDayEndTime] = useState<string>('16:00')
  const [maxSessionsPerDay, setMaxSessionsPerDay] = useState<number>(2)

  // Subject requirements state: for each subject, target sessions, resource, room
  const [requirements, setRequirements] = useState<SolverSubjectRequirement[]>(() => {
    return subjects.map((s) => ({
      subject_id: s.id,
      required_sessions: 3,
      resource_id: resources[0]?.id,
      room: 'Room 101'
    }))
  })

  const [solverResult, setSolverResult] = useState<SolverResult | null>(null)
  const [isSolving, setIsSolving] = useState<boolean>(false)

  if (!isAutoGenerateModalOpen) return null

  // Ensure requirements are in sync with subjects
  const currentReqs: SolverSubjectRequirement[] = subjects.map((s) => {
    const existing = requirements.find((r) => r.subject_id === s.id)
    return (
      existing || {
        subject_id: s.id,
        required_sessions: 2,
        resource_id: resources[0]?.id,
        room: ''
      }
    )
  })

  const updateRequirement = (subjectId: string, patch: Partial<SolverSubjectRequirement>): void => {
    const updated = currentReqs.map((r) => (r.subject_id === subjectId ? { ...r, ...patch } : r))
    setRequirements(updated)
  }

  const toggleDay = (day: number): void => {
    if (selectedDays.includes(day)) {
      if (selectedDays.length > 1) {
        setSelectedDays(selectedDays.filter((d) => d !== day))
      }
    } else {
      setSelectedDays([...selectedDays, day].sort())
    }
  }

  const handleRunSolver = async (): Promise<void> => {
    if (!activeTimetableId) return
    setIsSolving(true)
    setSolverResult(null)

    try {
      // Build discrete time slots
      const [startH] = dayStartTime.split(':').map(Number)
      const [endH] = dayEndTime.split(':').map(Number)
      const slots: Array<{ start: string; end: string }> = []

      let currentMin = startH * 60
      const endMin = endH * 60

      while (currentMin + slotDuration <= endMin) {
        const sH = Math.floor(currentMin / 60)
        const sM = currentMin % 60
        const eH = Math.floor((currentMin + slotDuration) / 60)
        const eM = (currentMin + slotDuration) % 60

        slots.push({
          start: `${String(sH).padStart(2, '0')}:${String(sM).padStart(2, '0')}`,
          end: `${String(eH).padStart(2, '0')}:${String(eM).padStart(2, '0')}`
        })

        currentMin += slotDuration
      }

      const result = await window.api.timetables.autoGenerate({
        timetable_id: activeTimetableId,
        days: selectedDays,
        time_slots: slots,
        requirements: currentReqs,
        resources,
        subjects,
        max_sessions_per_day: maxSessionsPerDay
      })

      setSolverResult(result)
    } catch (err) {
      console.error('Solver error:', err)
    } finally {
      setIsSolving(false)
    }
  }

  const handleApplyRoster = async (): Promise<void> => {
    if (!solverResult || solverResult.slots.length === 0) return
    await applyAutoGeneratedSlots(solverResult.slots)
    setIsAutoGenerateModalOpen(false)
  }

  const dayNames = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']

  return (
    <div className="fixed inset-0 bg-black/60 backdrop-blur-xs flex items-center justify-center p-4 z-50 text-[var(--text-primary)]">
      <div className="bg-[var(--bg-elevated)] border border-[var(--border-subtle)] rounded-[var(--radius-lg)] max-w-2xl w-full max-h-[90vh] flex flex-col shadow-xl overflow-hidden">
        {/* Header */}
        <div className="p-4 border-b border-[var(--border-subtle)] flex items-center justify-between bg-[var(--bg-sidebar)]">
          <div className="flex items-center gap-2.5">
            <div className="w-7 h-7 rounded-[var(--radius-sm)] bg-[var(--accent)] text-[var(--accent-text)] flex items-center justify-center">
              <Sparkles className="w-4 h-4 stroke-[2]" />
            </div>
            <div>
              <h2 className="text-sm font-semibold tracking-tight text-[var(--text-primary)]">
                Auto-Generate Timetable Roster
              </h2>
              <p className="text-[11px] text-[var(--text-muted)]">
                Constraint-based solver assigns sessions without room or trainer double-booking.
              </p>
            </div>
          </div>
          <button
            onClick={() => setIsAutoGenerateModalOpen(false)}
            className="p-1 text-[var(--text-muted)] hover:text-[var(--text-primary)] rounded transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Form Body */}
        <div className="p-5 overflow-y-auto space-y-4 flex-1">
          {/* Working Days */}
          <div>
            <label className="text-[10px] font-semibold text-[var(--text-muted)] uppercase tracking-wider block mb-1.5">
              Roster Working Days
            </label>
            <div className="flex gap-1.5">
              {[1, 2, 3, 4, 5, 6, 7].map((d) => {
                const isSelected = selectedDays.includes(d)
                return (
                  <button
                    key={d}
                    type="button"
                    onClick={() => toggleDay(d)}
                    className={`px-3 py-1 rounded-[var(--radius-sm)] text-xs font-semibold transition-all ${
                      isSelected
                        ? 'bg-[var(--accent)] text-[var(--accent-text)] shadow-xs'
                        : 'bg-[var(--bg-subtle)] border border-[var(--border-subtle)] text-[var(--text-secondary)] hover:text-[var(--text-primary)]'
                    }`}
                  >
                    {dayNames[d - 1]}
                  </button>
                )
              })}
            </div>
          </div>

          {/* Time & Constraints */}
          <div className="grid grid-cols-3 gap-3 p-3 bg-[var(--bg-subtle)]/60 rounded-[var(--radius-md)] border border-[var(--border-subtle)]">
            <div>
              <label className="text-[10px] font-semibold text-[var(--text-muted)] uppercase tracking-wider block mb-1">
                Hours (Start → End)
              </label>
              <div className="flex items-center gap-1">
                <input
                  type="time"
                  value={dayStartTime}
                  onChange={(e) => setDayStartTime(e.target.value)}
                  className="w-full bg-[var(--bg-elevated)] border border-[var(--border-subtle)] rounded px-2 py-1 text-xs text-[var(--text-primary)] focus:outline-none"
                />
                <span className="text-[var(--text-muted)]">-</span>
                <input
                  type="time"
                  value={dayEndTime}
                  onChange={(e) => setDayEndTime(e.target.value)}
                  className="w-full bg-[var(--bg-elevated)] border border-[var(--border-subtle)] rounded px-2 py-1 text-xs text-[var(--text-primary)] focus:outline-none"
                />
              </div>
            </div>

            <div>
              <label className="text-[10px] font-semibold text-[var(--text-muted)] uppercase tracking-wider block mb-1">
                Slot Length
              </label>
              <select
                value={slotDuration}
                onChange={(e) => setSlotDuration(Number(e.target.value))}
                className="w-full bg-[var(--bg-elevated)] border border-[var(--border-subtle)] rounded px-2 py-1.5 text-xs text-[var(--text-primary)] focus:outline-none"
              >
                <option value={45}>45 Minutes</option>
                <option value={60}>60 Minutes (1 Hour)</option>
                <option value={90}>90 Minutes (1.5 Hours)</option>
                <option value={120}>120 Minutes (2 Hours)</option>
              </select>
            </div>

            <div>
              <label className="text-[10px] font-semibold text-[var(--text-muted)] uppercase tracking-wider block mb-1">
                Max Per Subject/Day
              </label>
              <input
                type="number"
                min="1"
                max="5"
                value={maxSessionsPerDay}
                onChange={(e) => setMaxSessionsPerDay(Number(e.target.value))}
                className="w-full bg-[var(--bg-elevated)] border border-[var(--border-subtle)] rounded px-2 py-1 text-xs text-[var(--text-primary)] focus:outline-none"
              />
            </div>
          </div>

          {/* Subject Quotas */}
          <div>
            <div className="flex items-center justify-between mb-2">
              <label className="text-[10px] font-semibold text-[var(--text-muted)] uppercase tracking-wider">
                Weekly Subject Requirements ({subjects.length} subjects)
              </label>
            </div>

            {subjects.length === 0 ? (
              <div className="p-4 border border-[var(--border-subtle)] rounded-[var(--radius-md)] text-center text-xs text-[var(--text-muted)]">
                Add subjects first to auto-generate weekly schedules.
              </div>
            ) : (
              <div className="space-y-2 max-h-48 overflow-y-auto pr-1">
                {currentReqs.map((req) => {
                  const sub = subjects.find((s) => s.id === req.subject_id)
                  return (
                    <div
                      key={req.subject_id}
                      className="p-2.5 bg-[var(--bg-subtle)] border border-[var(--border-subtle)] rounded-[var(--radius-sm)] flex items-center justify-between gap-3 text-xs"
                    >
                      <div className="flex items-center gap-2 w-36 truncate">
                        <span className="w-2 h-2 rounded-full bg-[var(--accent)] shrink-0" />
                        <span className="font-semibold truncate">{sub?.name || 'Subject'}</span>
                      </div>

                      <div className="flex items-center gap-2">
                        <div className="flex items-center gap-1">
                          <span className="text-[10px] text-[var(--text-muted)]">Sessions/Wk:</span>
                          <input
                            type="number"
                            min="1"
                            max="10"
                            value={req.required_sessions}
                            onChange={(e) =>
                              updateRequirement(req.subject_id, {
                                required_sessions: Number(e.target.value)
                              })
                            }
                            className="w-12 bg-[var(--bg-elevated)] border border-[var(--border-subtle)] rounded px-1.5 py-0.5 text-xs text-center"
                          />
                        </div>

                        <select
                          value={req.resource_id || ''}
                          onChange={(e) =>
                            updateRequirement(req.subject_id, { resource_id: e.target.value })
                          }
                          className="bg-[var(--bg-elevated)] border border-[var(--border-subtle)] rounded px-2 py-0.5 text-xs"
                        >
                          <option value="">Unassigned Trainer</option>
                          {resources
                            .filter((r) => r.type === 'person')
                            .map((r) => (
                              <option key={r.id} value={r.id}>
                                {r.name}
                              </option>
                            ))}
                        </select>

                        <input
                          type="text"
                          placeholder="Room"
                          value={req.room || ''}
                          onChange={(e) =>
                            updateRequirement(req.subject_id, { room: e.target.value })
                          }
                          className="w-20 bg-[var(--bg-elevated)] border border-[var(--border-subtle)] rounded px-2 py-0.5 text-xs"
                        />
                      </div>
                    </div>
                  )
                })}
              </div>
            )}
          </div>

          {/* Solver Feedback Report */}
          {solverResult && (
            <div
              className={`p-3.5 rounded-[var(--radius-md)] border text-xs space-y-2 ${
                solverResult.success
                  ? 'bg-emerald-500/10 border-emerald-500/30 text-emerald-400'
                  : 'bg-amber-500/10 border-amber-500/30 text-amber-400'
              }`}
            >
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-2 font-semibold">
                  {solverResult.success ? (
                    <CheckCircle2 className="w-4 h-4 text-emerald-500" />
                  ) : (
                    <AlertTriangle className="w-4 h-4 text-amber-500" />
                  )}
                  <span>{solverResult.message}</span>
                </div>
                <span className="font-mono font-bold text-[11px]">
                  {solverResult.slots.length} slots generated
                </span>
              </div>

              {solverResult.slots.length > 0 && (
                <div className="pt-2 border-t border-current/20 flex items-center justify-between">
                  <span className="text-[11px] opacity-80">
                    Ready to populate into the current active timetable grid.
                  </span>
                  <button
                    type="button"
                    onClick={handleApplyRoster}
                    className="btn-primary text-xs py-1 px-3 shadow-xs"
                  >
                    Apply Roster to Grid
                  </button>
                </div>
              )}
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="p-3.5 border-t border-[var(--border-subtle)] bg-[var(--bg-sidebar)] flex items-center justify-between">
          <button
            type="button"
            onClick={() => setIsAutoGenerateModalOpen(false)}
            className="btn-secondary text-xs py-1 px-3"
          >
            Cancel
          </button>

          <button
            type="button"
            disabled={isSolving || subjects.length === 0}
            onClick={handleRunSolver}
            className="btn-primary flex items-center gap-1.5 py-1 px-3.5 text-xs font-semibold shadow-xs disabled:opacity-50"
          >
            <Sparkles className="w-3.5 h-3.5 stroke-[2]" />
            <span>{isSolving ? 'Solving Constraints...' : 'Generate Conflict-Free Roster'}</span>
          </button>
        </div>
      </div>
    </div>
  )
}
